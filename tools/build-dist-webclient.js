// Builds dist-webclient/ from webclient/, for publishing to IPFS.
//
// webclient/ stays a zero-build, dependency-free set of static files, which
// is what makes it servable straight from any IPFS gateway. This script only
// assembles the publishing artifact: it inlines webclient/app.js into
// index.html so the client is one self-contained file.
//
// That matters because the currently deployed client is a raw single-file
// CID (bafkrei..., no directory structure), which cannot resolve a separate
// "./app.js" from a <script src>. The previously deployed copy was inlined
// by hand and had already drifted from webclient/app.js by the time it was
// inspected, which is what this script exists to prevent. Node stdlib only,
// no dependencies.
"use strict";

const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const src = path.join(root, "webclient");
const out = path.join(root, "dist-webclient");

const NOTE = `<!--
  BUILD NOTE: single-file build of the Kaspanet web client, generated by
  tools/build-dist-webclient.js from webclient/index.html and
  webclient/app.js. Do not edit this file; edit those and rebuild with

      node tools/build-dist-webclient.js

  app.js is inlined below so this file works when pinned on its own as a
  raw single-file CID, which has no directory structure and so cannot
  resolve a separate "./app.js". opensearch.xml sits beside it for a
  folder upload; in a single-file pin the search link is simply inert.
-->`;

const html = fs.readFileSync(path.join(src, "index.html"), "utf8");
const app = fs.readFileSync(path.join(src, "app.js"), "utf8");

const TAG = '<script src="./app.js"></script>';
if (!html.includes(TAG)) {
  console.error("build failed: webclient/index.html no longer contains " + TAG);
  process.exit(1);
}
// A literal "</script>" inside the source would close the inline block early.
if (/<\/script/i.test(app)) {
  console.error("build failed: webclient/app.js contains a </script> sequence and cannot be inlined as is");
  process.exit(1);
}

let dist = html.replace(TAG, "<script>\n" + app + "\n</script>");
dist = dist.replace("<html lang=\"en\">", NOTE + "\n<html lang=\"en\">");

fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, "index.html"), dist);
fs.copyFileSync(path.join(src, "opensearch.xml"), path.join(out, "opensearch.xml"));

console.log("wrote dist-webclient/index.html (" + dist.length + " bytes)");
console.log("wrote dist-webclient/opensearch.xml");
